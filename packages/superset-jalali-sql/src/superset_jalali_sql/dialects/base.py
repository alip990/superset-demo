from typing import Protocol, Iterable
class Dialect(Protocol):
    def date_of(self, col: str) -> str: ...
    def values_table(self, rows: Iterable, alias: str, columns: tuple) -> str: ...
    def days_between(self, a: str, b: str) -> str: ...
    def lpad2(self, x: str) -> str: ...
    def to_text(self, x: str) -> str: ...
    def concat(self, *parts: str) -> str: ...
    def persian_digits(self, x: str) -> str: ...
    def sat_weekday(self, date: str) -> str: ...
